//! Triage of the independent M12 review claims V3 and V4 (verifier side).
//! Tests marked `#[ignore = "FINDING ..."]` assert the CORRECT behaviour and fail today; the others pin the facts the verdicts rely on.
mod common;
use common::*;
use setl8_verify::{FindingClass as C, Verdict};
use std::process::Command;

/// The journal with its newest line dropped, plus the snapshot of the COMPLETE journal (what the chain stores).
fn truncated_with_chain_snapshot() -> (Files, String) {
    let full = meta_only(3);
    let mut cut = full.clone();
    let last = cut.lines.len() - 1;
    cut.remove_lines(&[last]);
    let mut f = cut.files();
    f.snapshot = None;
    (f, full.snapshot_json())
}

/// V3 pin: a log that lost its tail is VALID without the snapshot and MISMATCH with the chain's snapshot.
#[test]
fn v3_pin_a_truncated_tail_is_valid_without_a_snapshot_and_a_mismatch_with_one() {
    let (mut f, snap) = truncated_with_chain_snapshot();
    let r = setl8_verify::verify_account(&f.inputs()).unwrap();
    assert_eq!((r.verdict, r.classes()), (Verdict::Valid, vec![]), "{:#?}", r.findings);
    f.snapshot = Some(snap.into_bytes());
    let r = setl8_verify::verify_account(&f.inputs()).unwrap();
    assert_eq!(r.verdict, Verdict::Mismatch);
    assert!(!r.classes().is_empty(), "the chain snapshot (seq 3) disagrees with the truncated replay (seq 2)");
}

// FINDING V3
/// Without `--snapshot` the CLI prints a plain `VERDICT: VALID` although nothing ties the replayed head to the chain: a log that
/// lost its tail (or was regenerated by the party that serves it) is indistinguishable. The verdict must say it is unanchored.
#[test]
fn v3_a_verdict_without_a_chain_snapshot_must_say_it_is_unanchored() {
    let (f, _) = truncated_with_chain_snapshot();
    let dir = std::env::temp_dir().join(format!("sl8verify-triage-v3-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    for (name, bytes) in [("events.jsonl", &f.events), ("rules.json", &f.rules), ("archive.bin", &f.archive), ("intents.jsonl", &f.intents)] {
        std::fs::write(dir.join(name), bytes).unwrap();
    }
    let p = |n: &str| dir.join(n).to_string_lossy().to_string();
    let out = Command::new(env!("CARGO_BIN_EXE_setl8-verify"))
        .args(["account", "--events", &p("events.jsonl"), "--rules", &p("rules.json"), "--archive", &p("archive.bin"), "--intents", &p("intents.jsonl")])
        .output()
        .unwrap();
    let text = String::from_utf8(out.stdout).unwrap().to_lowercase();
    assert!(text.contains("not anchored to the chain"), "{text}");
}

/// A valid pass request that the trader then cancels (`cancel_pass`, DESIGN 10.3 / 6.2), followed by the program's `PassCancelled`.
fn cancelled_pass_log() -> Bundle {
    let mut b = pass_case(0);
    let (seq, t) = (b.last_seq(), last_event_time(&b));
    b.push_pass_requested(2, 8_000_000_000, 108_000_000_000, seq, t);
    b.push_raw(&format!("\"type\":\"pass_cancelled\",\"phase\":2,\"time\":{}", t + 3_600));
    b
}

// FINDING V4
#[test]
fn v4_watch_must_not_treat_a_cancelled_pass_as_pending() {
    let b = cancelled_pass_log();
    let text = b.events_text();
    assert_eq!(setl8_verify::cli::newest_pending_pass(text.as_bytes()), None);
}

// FINDING V4
#[test]
fn v4_a_pass_cancelled_line_must_not_be_an_unknown_event() {
    let r = verify_no_snapshot(&cancelled_pass_log());
    assert!(!r.classes().contains(&C::UnknownEvent), "{:#?}", r.findings);
}

/// V4 pin: with no pass line in the log at all, `watch` answers NO_PENDING_PASS and exit 0 (it cannot know the chain has one).
#[test]
fn v4_pin_watch_without_any_pass_line_is_exit_0() {
    let b = pass_case(0);
    assert_eq!(setl8_verify::cli::newest_pending_pass(b.events_text().as_bytes()), None);
}
